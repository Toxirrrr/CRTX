import * as fs from 'fs';
import * as path from 'path';
import { ContextCatalog, PrismaModel, DtoDefinition, ApiEndpoint } from './types';

export interface GeneratedDocFiles {
  databaseModelsPath: string;
  dtoCatalogPath: string;
  apiEndpointsPath: string;
  codebaseTruthPath: string;
  jsonContractsPath: string;
}

export function generateLivingDocuments(catalog: ContextCatalog, projectRoot: string): GeneratedDocFiles {
  const contractsDir = path.join(projectRoot, 'docs', 'contracts');
  const aiContextDir = path.join(projectRoot, 'docs', 'ai-context');

  if (!fs.existsSync(contractsDir)) {
    fs.mkdirSync(contractsDir, { recursive: true });
  }
  if (!fs.existsSync(aiContextDir)) {
    fs.mkdirSync(aiContextDir, { recursive: true });
  }

  // 1. Generate docs/contracts/DATABASE_MODELS.md
  let dbMarkdown = `# Database Models & Schema Catalog (Prisma Truth)

> **AUTOGENERATED LIVING DOCUMENT** — Do not edit manually.  
> Last synchronized: \`${catalog.generatedAt}\`  
> Total Models: **${catalog.stats.modelCount}** | Total Enums: **${catalog.stats.enumCount}**

This document represents the absolute database schema truth derived directly from \`server/prisma/schema.prisma\`.

---

## 1. Enums (${catalog.stats.enumCount})

| Enum Name | Allowed Values |
|-----------|----------------|
`;

  for (const [enumName, enumData] of Object.entries(catalog.enums).sort((a, b) => a[0].localeCompare(b[0]))) {
    dbMarkdown += `| \`${enumName}\` | \`${enumData.values.join('`, `')}\` |\n`;
  }

  dbMarkdown += `\n---\n\n## 2. Models (${catalog.stats.modelCount})\n\n`;

  for (const [modelName, model] of Object.entries(catalog.models).sort((a, b) => a[0].localeCompare(b[0]))) {
    dbMarkdown += `### \`${modelName}\`\n\n`;
    if (model.documentation) {
      dbMarkdown += `> ${model.documentation}\n\n`;
    }
    dbMarkdown += `| Field | Type | Required | Key / Relation | Default | Documentation |\n`;
    dbMarkdown += `|-------|------|----------|----------------|---------|---------------|\n`;

    for (const f of model.fields) {
      let keyRel = '';
      if (f.isId) keyRel = '🔑 Primary Key';
      else if (f.isUnique) keyRel = '⚡ Unique';
      else if (f.isRelation) keyRel = `🔗 -> ${f.relationTarget || 'Model'}`;

      const reqStr = f.isRequired ? '✅ Yes' : '❌ No';
      const typeStr = f.isList ? `\`${f.type}[]\`` : `\`${f.type}\``;
      const defStr = f.defaultValue ? `\`${f.defaultValue}\`` : '-';
      const docStr = f.documentation || '-';

      dbMarkdown += `| \`${f.name}\` | ${typeStr} | ${reqStr} | ${keyRel || '-'} | ${defStr} | ${docStr} |\n`;
    }
    dbMarkdown += `\n`;
  }

  const databaseModelsPath = path.join(contractsDir, 'DATABASE_MODELS.md');
  fs.writeFileSync(databaseModelsPath, dbMarkdown, 'utf-8');

  // 2. Generate docs/contracts/DTO_CATALOG.md
  let dtoMarkdown = `# TypeScript DTO & Contract Catalog (Backend Truth)

> **AUTOGENERATED LIVING DOCUMENT** — Do not edit manually.  
> Last synchronized: \`${catalog.generatedAt}\`  
> Total DTOs / Interfaces: **${catalog.stats.dtoCount}**

This document catalogues all class-based DTOs and interfaces extracted directly from the codebase AST.

---

## DTO Definitions (${catalog.stats.dtoCount})

`;

  for (const [dtoName, dto] of Object.entries(catalog.dtos).sort((a, b) => a[0].localeCompare(b[0]))) {
    const relFile = path.relative(projectRoot, dto.filePath).replace(/\\/g, '/');
    dtoMarkdown += `### \`${dtoName}\`${dto.extendsClass ? ` *(extends ${dto.extendsClass})*` : ''}\n\n`;
    dtoMarkdown += `*File: \`[${relFile}](file:///${dto.filePath.replace(/\\/g, '/')})\`*\n\n`;

    if (dto.properties.length === 0) {
      dtoMarkdown += `*(No explicitly defined properties)*\n\n`;
      continue;
    }

    dtoMarkdown += `| Property | Type | Optional | Validation Rules | Description |\n`;
    dtoMarkdown += `|----------|------|----------|------------------|-------------|\n`;

    for (const p of dto.properties) {
      const optStr = p.isOptional ? '❓ Optional' : '❗ Required';
      const valRules = p.validationRules.length > 0 ? `\`${p.validationRules.join('`, `')}\`` : '-';
      const descStr = p.description || '-';
      dtoMarkdown += `| \`${p.name}\` | \`${p.type}\` | ${optStr} | ${valRules} | ${descStr} |\n`;
    }
    dtoMarkdown += `\n`;
  }

  const dtoCatalogPath = path.join(contractsDir, 'DTO_CATALOG.md');
  fs.writeFileSync(dtoCatalogPath, dtoMarkdown, 'utf-8');

  // 3. Generate docs/contracts/API_ENDPOINTS.md
  let apiMarkdown = `# HTTP API Endpoints & Surface Catalog

> **AUTOGENERATED LIVING DOCUMENT** — Do not edit manually.  
> Last synchronized: \`${catalog.generatedAt}\`  
> Total Endpoints: **${catalog.stats.endpointCount}**

Endpoints are grouped by their canonical surface: \`ORGANIZATION\`, \`PLATFORM\`, \`MOBILE\`, and \`SYSTEM\`.

---
`;

  const surfaces: ('ORGANIZATION' | 'PLATFORM' | 'MOBILE' | 'SYSTEM' | 'UNKNOWN')[] = [
    'ORGANIZATION',
    'PLATFORM',
    'MOBILE',
    'SYSTEM'
  ];

  for (const surface of surfaces) {
    const surfaceEndpoints = catalog.endpoints.filter(e => e.surface === surface);
    apiMarkdown += `\n## Surface: \`${surface}\` (${surfaceEndpoints.length} endpoints)\n\n`;

    // Group endpoints by Domain Module within this surface (NOW: Flat -> AFTERUPDATE: Hierarchical SURFACE[MODULE[ENDPOINTS]])
    const moduleMap: Record<string, typeof surfaceEndpoints> = {};
    for (const ep of surfaceEndpoints) {
      let moduleName = 'General';
      if (ep.summary && ep.summary.includes(':')) {
        moduleName = ep.summary.split(':')[0].trim();
      } else if (ep.controllerName) {
        moduleName = ep.controllerName.replace(/Controller$/, '');
      }
      if (!moduleMap[moduleName]) {
        moduleMap[moduleName] = [];
      }
      moduleMap[moduleName].push(ep);
    }

    const sortedModules = Object.keys(moduleMap).sort();
    for (const mod of sortedModules) {
      const modEndpoints = moduleMap[mod];
      apiMarkdown += `### Module: \`${mod}\` (${modEndpoints.length} endpoints)\n\n`;
      apiMarkdown += `| Method | Full Route | Body DTO | Roles / Permissions | Summary |\n`;
      apiMarkdown += `|--------|------------|----------|---------------------|---------|\n`;

      for (const ep of modEndpoints.sort((a, b) => a.fullPath.localeCompare(b.fullPath))) {
        const rolesStr = ep.roles.length > 0 ? `Roles: \`${ep.roles.join(', ')}\`` : '';
        const permStr = ep.permissions.length > 0 ? `Perms: \`${ep.permissions.join(', ')}\`` : '';
        const authStr = [rolesStr, permStr].filter(Boolean).join('; ') || 'Public / OrgScope';
        const bodyStr = ep.bodyDto ? `\`${ep.bodyDto}\`` : '-';
        const summaryStr = ep.summary || ep.methodName;

        apiMarkdown += `| \`${ep.method}\` | \`${ep.fullPath}\` | ${bodyStr} | ${authStr} | ${summaryStr} |\n`;
      }
      apiMarkdown += `\n`;
    }
  }

  const apiEndpointsPath = path.join(contractsDir, 'API_ENDPOINTS.md');
  fs.writeFileSync(apiEndpointsPath, apiMarkdown, 'utf-8');

  // 4. Generate docs/ai-context/CODEBASE_TRUTH.md
  let aiTruth = `# Codebase Living Context & Entity Truth

> **AI CONTEXT ENGINE MASTER SHEET**  
> Generated: \`${catalog.generatedAt}\`  
> Models: **${catalog.stats.modelCount}** | DTOs: **${catalog.stats.dtoCount}** | Endpoints: **${catalog.stats.endpointCount}**

This document serves as the high-density runtime truth for AI agents working in this workspace.

---

## 1. Core Prisma Entities & Primary Identifiers

`;

  for (const [name, model] of Object.entries(catalog.models).slice(0, 30)) {
    const idField = model.fields.find(f => f.isId)?.name || 'id';
    const scalarFields = model.fields.filter(f => !f.isRelation).map(f => f.name).slice(0, 8).join(', ');
    aiTruth += `- **\`${name}\`** (PK: \`${idField}\`): \`${scalarFields}...\`\n`;
  }

  aiTruth += `\n*(Full list of ${catalog.stats.modelCount} models in \`docs/contracts/DATABASE_MODELS.md\`)*\n\n`;

  aiTruth += `---

## 2. API Surface Topology

- **ORGANIZATION Surface**: Tenant-scoped operations (\`OrganizationGuard\`, \`PermissionsGuard\`).
- **PLATFORM Surface**: Platform administration (\`PLATFORM_OWNER\`, \`PLATFORM_MANAGER\`).
- **MOBILE Surface**: Field agent operations, lightweight offline payloads.
- **SYSTEM Surface**: Infrastructure, Prometheus metrics, health checks.

---

## 3. Realtime Socket.io Gateways

| Namespace | Event | Direction | Payload |
|-----------|-------|-----------|---------|
`;

  for (const ev of catalog.socketEvents) {
    aiTruth += `| \`${ev.namespace}\` | \`${ev.event}\` | \`${ev.direction}\` | \`${ev.payloadType || 'any'}\` |\n`;
  }

  const codebaseTruthPath = path.join(aiContextDir, 'CODEBASE_TRUTH.md');
  fs.writeFileSync(codebaseTruthPath, aiTruth, 'utf-8');

  // 5. Generate docs/contracts/codebase-contracts.json
  const jsonContractsPath = path.join(contractsDir, 'codebase-contracts.json');
  fs.writeFileSync(jsonContractsPath, JSON.stringify(catalog, null, 2), 'utf-8');

  return {
    databaseModelsPath,
    dtoCatalogPath,
    apiEndpointsPath,
    codebaseTruthPath,
    jsonContractsPath
  };
}
